async function seed() {
  console.log(`Starting seeding of ${PRODUCTS_DATA.length} products into Supabase...`);

  // 1. Clean slate: Delete existing product_images and products
  console.log('Clearing old product images and products...');
  const { error: delImgErr } = await supabase
    .from('product_images')
    .delete()
    .neq('id', '00000000-0000-0000-0000-000000000000');
  if (delImgErr) console.warn('Warning clearing product_images:', delImgErr.message);

  const { error: delProdErr } = await supabase
    .from('products')
    .delete()
    .neq('id', '00000000-0000-0000-0000-000000000000');
  if (delProdErr) console.warn('Warning clearing products:', delProdErr.message);

  // 2. Prepare database rows for batch insertion
  const productRows = [];
  const imageRows = [];

  for (let i = 0; i < PRODUCTS_DATA.length; i++) {
    const p = PRODUCTS_DATA[i];
    const index = i + 1;
    const productUid = createDeterministicUuid(index);
    const classId = CLASS_IDS[p.classCode] || CLASS_IDS['I'];
    const categoryId = CATEGORY_IDS[p.categorySlug] || CATEGORY_IDS['kit'];

    productRows.push({
      id: productUid,
      sku: p.sku,
      class_id: classId,
      category_id: categoryId,
      name: p.name,
      subtitle: p.subtitle,
      price: p.price,
      original_price: p.originalPrice || null,
      rating: 4.8 + ((index % 3) * 0.1),
      review_count: 15 + ((index * 3) % 70),
      audience: p.audience || 'both',
      is_new: index > 70 || index % 4 === 0,
      is_featured: index % 6 === 0,
      in_stock: true,
      stock_count: p.stockCount,
      badge: p.badge || 'NEW ARRIVAL',
      sizes: p.sizes,
      colors: p.colors,
      features: p.features,
      specifications: p.specifications,
      keywords: p.keywords,
      description: p.description,
      created_at: new Date(Date.now() - (PRODUCTS_DATA.length - i) * 3600000).toISOString(),
    });

    // Relational images
    p.images.forEach((imgPath, imgIdx) => {
      imageRows.push({
        id: createImageUuid(index, imgIdx + 1),
        product_id: productUid,
        image_path: imgPath,
        display_order: imgIdx + 1,
        is_primary: imgIdx === 0,
        alt_text: `${p.name} - View ${imgIdx + 1}`,
      });
    });
  }

  // 3. Batch insert products (in chunks of 25 for safe transmission)
  console.log(`Inserting ${productRows.length} product records in batches...`);
  const chunkSize = 25;
  for (let c = 0; c < productRows.length; c += chunkSize) {
    const chunk = productRows.slice(c, c + chunkSize);
    const { error: insErr } = await supabase.from('products').insert(chunk);
    if (insErr) {
      console.error(`Error inserting products chunk ${c}-${c + chunkSize}:`, insErr.message);
      throw insErr;
    }
    console.log(`  - Inserted products chunk ${c + 1} to ${Math.min(c + chunkSize, productRows.length)}`);
  }

  // 4. Batch insert product images (in chunks of 50)
  console.log(`Inserting ${imageRows.length} product image records in batches...`);
  const imgChunkSize = 50;
  for (let c = 0; c < imageRows.length; c += imgChunkSize) {
    const chunk = imageRows.slice(c, c + imgChunkSize);
    const { error: imgInsErr } = await supabase.from('product_images').insert(chunk);
    if (imgInsErr) {
      console.error(`Error inserting images chunk ${c}-${c + imgChunkSize}:`, imgInsErr.message);
      throw imgInsErr;
    }
    console.log(`  - Inserted images chunk ${c + 1} to ${Math.min(c + imgChunkSize, imageRows.length)}`);
  }

  // 5. Final verification
  const { count: finalProdCount } = await supabase.from('products').select('*', { count: 'exact', head: true });
  const { count: finalImgCount } = await supabase.from('product_images').select('*', { count: 'exact', head: true });

  console.log('====================================================');
  console.log('SEEDING COMPLETE! Database verification summary:');
  console.log(`Total Products in Supabase:     ${finalProdCount}`);
  console.log(`Total Product Images in DB:    ${finalImgCount}`);
  console.log('====================================================');

  // Breakdown by category
  for (const [slug, catId] of Object.entries(CATEGORY_IDS)) {
    const { count } = await supabase.from('products').select('*', { count: 'exact', head: true }).eq('category_id', catId);
    console.log(`- Category "${slug.padEnd(22)}": ${count} products`);
  }

  // Breakdown by class
  for (const [code, clsId] of Object.entries(CLASS_IDS)) {
    const { count } = await supabase.from('products').select('*', { count: 'exact', head: true }).eq('class_id', clsId);
    console.log(`- Class "${code}":                          ${count} products`);
  }
}

seed().catch((err) => {
  console.error('Fatal seeding error:', err);
  process.exit(1);
});
